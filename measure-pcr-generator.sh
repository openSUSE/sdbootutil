#!/bin/bash
set -euo pipefail

# For a generator, the first parameter `normal-dir` is not optional
[ -n "$1" ] || { echo "Missing normal-dir parameter"; exit 1; }

[ -f "/etc/crypttab" ] || exit 0

# Only the entries in /etc/crypttab in the initrd should participate
# from the extension for now.  The reason is that extensions after the
# switch root cannot participate in abort the boot process from initrd
# itself
[ -f "/etc/initrd-release" ] || exit 0

# Read /etc/crypttab lines that contains tpm2-device and
# tpm2-measure-pcr.  It will order the services as listed in this file
after=""
anchor=""
while read -r name _ _ opts || [ -n "$name" ]; do
	[ -n "$name" ] || continue
	[[ "$name" = \#* ]] && continue
	[[ "$opts" != *"tpm2-device="* ]] && continue
	[[ "$opts" != *"tpm2-measure-pcr="* ]] && continue
	name="$(systemd-escape "$name")"
	mkdir -p "$1/systemd-cryptsetup@$name.service.d"
	cat > "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf" <<-EOF
	# Automatically generated by measure-pcr-generator

	[Service]
	Environment="SYSTEMD_FORCE_MEASURE=yes"
	EOF
	if [ -n "$after" ]; then
		cat >> "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf" <<-EOF

		[Unit]
		After=systemd-cryptsetup@$after.service
		EOF
	fi
	after="$name"
	[ -n "$anchor" ] || anchor="$name"
done < /etc/crypttab

# The other TPM2 devices unlock after the first measured one, the
# anchor.  Their TPM2 slots can be bound to the value of PCR 15 once the
# anchor is measured, so a device that starts before it would not
# unseal, and a swapped anchor (another volume key) would not unseal
# them either
if [ -n "$anchor" ]; then
	while read -r name _ _ opts || [ -n "$name" ]; do
		[ -n "$name" ] || continue
		[[ "$name" = \#* ]] && continue
		[[ "$opts" != *"tpm2-device="* ]] && continue
		[[ "$opts" == *"tpm2-measure-pcr="* ]] && continue
		name="$(systemd-escape "$name")"
		mkdir -p "$1/systemd-cryptsetup@$name.service.d"
		cat > "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf" <<-EOF
		# Automatically generated by measure-pcr-generator

		[Unit]
		After=systemd-cryptsetup@$anchor.service
		EOF
	done < /etc/crypttab
fi

# Do a similar loop for devices that can be unlocked by FIDO2 keys
after=""
while read -r name _ _ opts || [ -n "$name" ]; do
	[ -n "$name" ] || continue
	[[ "$name" = \#* ]] && continue
	[[ "$opts" != *"fido2-device="* ]] && continue
	name="$(systemd-escape "$name")"
	mkdir -p "$1/systemd-cryptsetup@$name.service.d"
	[ -f "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf" ] || {
		echo "# Automatically generated by measure-pcr-generator" > "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf"
	}
	if [ -n "$after" ]; then
		cat >> "$1/systemd-cryptsetup@$name.service.d/measure-pcr.conf" <<-EOF

		[Unit]
		After=systemd-cryptsetup@$after.service
		EOF
	fi
	after="$name"
done < /etc/crypttab
